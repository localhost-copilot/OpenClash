local policy = dofile("luci-app-openclash/luasrc/device_egress.lua")
local passed = 0
local function test(name, fn)
	local ok, err = pcall(fn)
	if not ok then error(name .. ": " .. tostring(err)) end
	passed = passed + 1
end
local lan = {{address = "192.168.50.1", prefix = 24}}
local function device(changes)
	local row = {enabled = "1", name = "MacBook <script>😀", mac = "AA:BB:CC:DD:EE:01", ip = "192.168.50.20", target = "香港 ' \" 😀"}
	for k, v in pairs(changes or {}) do row[k] = v end
	return row
end
local function contains(source, text) assert(source:find(text, 1, true), text) end
local function rejects(rows, message)
	local value, err = policy.validate(rows, lan)
	assert(not value and err == message, tostring(err))
end

test("guard matches MAC, source binding and actual LAN only", function()
	local result = assert(policy.render_guard({device()}, lan, {"fd00:50::/64"}))
	contains(result, "priority -10")
	contains(result, "priority -160")
	contains(result, "priority -149")
	contains(result, "ether saddr @bound meta mark != 0x40000 counter drop")
	contains(result, "ether saddr @bound counter drop")
	contains(result, "ether saddr AA:BB:CC:DD:EE:01 ip saddr != 192.168.50.20 counter drop")
	contains(result, "192.168.50.0/24")
	contains(result, "ip6 daddr @lan6 return")
	assert(not result:find("MacBook", 1, true) and not result:find("香港", 1, true))
	assert(not result:find("192.168.0.0/16", 1, true))
end)
test("disabled guard removes table", function()
	local result = assert(policy.render_guard({device({enabled = "0"})}, lan, {}))
	contains(result, "delete table inet openclash_guard")
	assert(not result:find("chain ", 1, true))
	assert(policy.render_guard({}, {}, {}) == result)
end)
test("invalid UCI cannot emit nft source", function()
	assert(not policy.render_guard({device({mac = "AA:BB:CC:DD:EE:01; flush ruleset"})}, lan, {}))
	assert(not policy.render_guard({device({enabled = "yes"})}, lan, {}))
	assert(not policy.render_guard({device()}, {}, {}))
	assert(not policy.render_guard({device()}, lan, {"::/0; flush ruleset"}))
end)
test("emergency blocks before normal interception and at forward/output", function()
	local result = policy.emergency()
	contains(result, "hook prerouting priority -300; policy drop")
	contains(result, 'fib daddr oifname "br-lan" accept')
	contains(result, "hook forward priority -10; policy drop")
	contains(result, "hook output priority -10; policy drop")
end)
test("opt-in conntrack fallback preserves other mark bits", function()
	local result = assert(policy.render_guard({device()}, lan, {}, true))
	contains(result, "ct mark set ct mark | 0x40000000")
	contains(result, "ct direction original ct mark & 0x40000000 != 0 counter drop")
	assert(not result:find("ether saddr @bound counter drop", 1, true))
end)
test("normalized UCI rows retain arbitrary text and reserve section ports", function()
	local rows = assert(policy.validate({device({enabled = "0"}), device({mac = "aa:bb:cc:dd:ee:02", ip = "192.168.50.21"})}, lan))
	assert(rows[2].mac == "AA:BB:CC:DD:EE:02" and rows[2].port == 7902)
	assert(rows[1].name == "MacBook <script>😀")
end)
test("MAC duplicate is case insensitive", function()
	rejects({device(), device({mac = "aa:bb:cc:dd:ee:01", ip = "192.168.50.21"})}, "This device already has an egress.")
end)
test("IP duplicate identifies other owner", function()
	local result, err, owner = policy.validate({device(), device({mac = "AA:BB:CC:DD:EE:02"})}, lan)
	assert(not result and err == "This IP is already used by %s." and owner == "MacBook <script>😀")
end)
test("router, foreign, network, broadcast and noncanonical IP rejected", function()
	rejects({device({ip = "192.168.50.1"})}, "The router's own address cannot be used.")
	for _, ip in ipairs({"192.168.51.20", "192.168.50.0", "192.168.50.255", "192.168.050.20", "192.168.50.999"}) do
		rejects({device({ip = ip})}, "IP is outside the LAN subnet %s.")
	end
end)
test("unicast MAC only", function()
	for _, mac in ipairs({"invalid", "01:00:5e:00:00:01", "FF:FF:FF:FF:FF:FF", "00:00:00:00:00:00"}) do
		rejects({device({mac = mac})}, "Invalid MAC address format.")
	end
end)
test("32 section boundary includes paused devices", function()
	local rows = {}
	for i = 1, 32 do rows[i] = device({enabled = "0", mac = string.format("02:00:00:00:00:%02X", i), ip = "192.168.50." .. (i + 10)}) end
	assert(policy.validate(rows, lan))
	rows[33] = device()
	rejects(rows, "A maximum of 32 devices is allowed.")
end)
test("unsafe and missing targets rejected but permitted for guard replay", function()
	local row = device({target = "Group"})
	local targets = {{name = "Group", unsafe = true}}
	local value, err = policy.validate({row}, lan, targets)
	assert(not value and err:find("contains DIRECT", 1, true))
	assert(not policy.validate({row}, lan, {}))
	assert(policy.validate({row}, lan, targets, true))
	rejects({device({target = ""})}, "Please select an egress.")
end)
test("runtime separates bound traffic before ordinary chains", function()
	local rows = assert(policy.validate({device()}, lan))
	local result = assert(policy.render_runtime(rows, {"openclash", "openclash_mangle", "openclash_v6", "openclash_mangle_v6", "openclash_output"}, false))
	contains(result, "priority -151")
	contains(result, "tproxy ip to :7901 meta mark set 0x40000")
	contains(result, "ether saddr AA:BB:CC:DD:EE:01 ip saddr 192.168.50.20 meta l4proto { tcp, udp }")
	contains(result, "insert rule inet fw4 openclash_mangle_v6 ether saddr @openclash_bound_macs")
	assert(not result:find("openclash_output", 1, true))
	assert(not result:find("th dport 53", 1, true))
end)
test("DNS hijack retained only when enabled", function()
	local result = assert(policy.render_runtime({device()}, {"openclash"}, true, 7874))
	contains(result, "priority -101")
	contains(result, "th dport 53 meta mark set 0x40000 return")
	contains(result, "th dport 53 redirect to :7874")
	assert(policy.render_runtime({device({enabled = "0"})}, {}, false) == "")
end)
test("status comparison discards only volatile nft metadata", function()
	local result = policy.canonical_table({nftables = {{metainfo = {version = "x"}}, {rule = {handle = 10, expr = {{counter = {packets = 2, bytes = 100}}, {drop = {}}}}}}})
	assert(#result == 1 and result[1].rule.handle == nil)
	assert(next(result[1].rule.expr[1].counter) == nil)
	assert(result[1].rule.expr[2].drop ~= nil)
end)
print("Device egress Lua: " .. passed .. " tests passed")
